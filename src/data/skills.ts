export const SKILLS: Record<string, SkillDef> = Object.fromEntries(list.map((s) => [s.id, s]));

/** Maps every evolved skill back to the base skill of its line. */
const ROOT: Record<string, string> = {};
for (const s of list) if (!ROOT[s.id]) {
  let cur: SkillDef | undefined = s;
  while (cur) {
    ROOT[cur.id] = s.id;
    cur = cur.evolvesTo ? SKILLS[cur.evolvesTo] : undefined;
  }
}

export function skillRoot(id: string): string {
  return ROOT[id] ?? id;
}

/** All skills in the same evolution line, base first. */
export function skillLine(rootId: string): SkillDef[] {
  const out: SkillDef[] = [];
  let cur: SkillDef | undefined = SKILLS[rootId];
  while (cur) {
    out.push(cur);
    cur = cur.evolvesTo ? SKILLS[cur.evolvesTo] : undefined;
  }
  return out;
}
